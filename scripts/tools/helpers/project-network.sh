#!/bin/sh
# Per-project Docker network. Each dynamic project gets baton-<project>, an
# --internal network shared only by its APP_SERVICE container and ingress
# nginx. nginx reaches the app at the alias baton-<project> on that network.
# See docs/design/per-project-networks.md.
#
#   . "$BASE_DIR/scripts/tools/helpers/project-network.sh"
#   host=$(baton_upstream_host "$PROJECT") || exit 1
#
# The caller sets BASE_DIR. docker comes from PATH.

# container_name of the nginx service in orchestrator/docker-compose.yml.
BATON_NGINX_CONTAINER=ingress-nginx

# Print baton-<project>: the network name, the nginx upstream host and the
# app's alias. The project name ends up in a DNS label, so it must be
# lower-case letters, digits and '-', not start with '-', and leave room for
# the prefix within 63 characters.
baton_upstream_host() {
  _buh=${1-}
  case $_buh in
    ''|-*|*[!a-z0-9-]*)
      echo "[project-network] ERROR: project name '$_buh' must be lower-case letters, digits and '-', not starting with '-'" >&2
      return 1
      ;;
  esac
  if [ "${#_buh}" -gt 57 ]; then
    echo "[project-network] ERROR: project name '$_buh' is longer than 57 characters" >&2
    return 1
  fi
  printf 'baton-%s\n' "$_buh"
}

# APP_SERVICE is a compose service name: [A-Za-z0-9][A-Za-z0-9._-]*. The
# baton- prefix is reserved for names baton creates.
baton_check_app_service() {
  case ${1-} in
    ''|[!A-Za-z0-9]*|*[!A-Za-z0-9._-]*|baton-*) return 1 ;;
  esac
  return 0
}

# Path of the generated file that attaches nginx to every project network
# whenever the orchestrator stack is (re)created.
baton_network_orchestrator_file() {
  printf '%s/orchestrator/docker-compose.networks.yml\n' "$BASE_DIR"
}

# Run docker compose for the orchestrator stack with the generated network
# list, so a (re)created nginx is attached to every project network before
# it starts. Use this for every up/down of the stack.
baton_orchestrator_compose() {
  _boc_base="$BASE_DIR/orchestrator/docker-compose.yml"
  _boc_nets=$(baton_network_orchestrator_file)
  if [ -f "$_boc_nets" ]; then
    docker compose -f "$_boc_base" -f "$_boc_nets" "$@"
  else
    docker compose -f "$_boc_base" "$@"
  fi
}

# $1 network. True when nginx is attached to it.
baton_network_has_nginx() {
  _bnhn=$(docker network inspect -f '{{range .Containers}} {{.Name}}{{end}}' "$1" 2>/dev/null) || return 1
  case "$_bnhn " in
    *" $BATON_NGINX_CONTAINER "*) return 0 ;;
  esac
  return 1
}

# Rewrite the orchestrator network list from the baton networks that exist.
# With none, the file is removed and the orchestrator runs on its base file.
baton_network_write_orchestrator_list() {
  _bnwl_file=$(baton_network_orchestrator_file)
  if ! _bnwl_nets=$(docker network ls --filter label=baton.project --format '{{.Name}}'); then
    echo "[project-network] ERROR: could not list baton networks" >&2
    return 1
  fi
  _bnwl_nets=$(printf '%s\n' "$_bnwl_nets" | sort -u)
  _bnwl_ok=
  for _bnwl_n in $_bnwl_nets; do
    case $_bnwl_n in
      baton-*[!a-z0-9-]*|baton-)
        echo "[project-network] WARNING: skipping network with an unexpected name: $_bnwl_n" >&2
        ;;
      baton-*) _bnwl_ok="$_bnwl_ok $_bnwl_n" ;;
      *) echo "[project-network] WARNING: skipping network with an unexpected name: $_bnwl_n" >&2 ;;
    esac
  done
  if [ -z "$_bnwl_ok" ]; then
    rm -f "$_bnwl_file"
    return 0
  fi
  _bnwl_tmp="$_bnwl_file.tmp.$$"
  {
    echo "# Generated by baton (scripts/tools/helpers/project-network.sh). Do not edit."
    echo "# Attaches ingress nginx to every project network when the orchestrator"
    echo "# stack is created, so a recreated nginx can resolve every upstream."
    echo "services:"
    echo "  nginx:"
    echo "    networks:"
    for _bnwl_n in $_bnwl_ok; do
      echo "      $_bnwl_n: {}"
    done
    echo "networks:"
    for _bnwl_n in $_bnwl_ok; do
      echo "  $_bnwl_n:"
      echo "    external: true"
    done
  } > "$_bnwl_tmp" || { rm -f "$_bnwl_tmp"; return 1; }
  mv -f "$_bnwl_tmp" "$_bnwl_file"
}

# $1 project. Create baton-<project> if missing, attach nginx, and refresh the
# orchestrator network list. An existing network must be one baton created.
baton_network_ensure() {
  _bne_net=$(baton_upstream_host "$1") || return 1
  if docker network inspect "$_bne_net" >/dev/null 2>&1; then
    _bne_label=$(docker network inspect -f '{{index .Labels "baton.project"}}' "$_bne_net") || return 1
    _bne_internal=$(docker network inspect -f '{{.Internal}}' "$_bne_net") || return 1
    if [ "$_bne_label" != "$1" ] || [ "$_bne_internal" != true ]; then
      echo "[project-network] ERROR: network $_bne_net exists but was not created by baton for $1 (remove it and deploy again)" >&2
      return 1
    fi
  else
    echo "[project-network] Creating internal network $_bne_net" >&2
    if ! docker network create --internal --label "baton.project=$1" "$_bne_net" >/dev/null; then
      echo "[project-network] ERROR: could not create network $_bne_net" >&2
      return 1
    fi
  fi
  if ! baton_network_has_nginx "$_bne_net"; then
    echo "[project-network] Attaching $BATON_NGINX_CONTAINER to $_bne_net" >&2
    if ! docker network connect "$_bne_net" "$BATON_NGINX_CONTAINER"; then
      echo "[project-network] ERROR: could not attach $BATON_NGINX_CONTAINER to $_bne_net" >&2
      return 1
    fi
  fi
  baton_network_write_orchestrator_list
}

# $1 project. Detach nginx, delete baton-<project>, refresh the list. Returns
# 1 when the network could not be removed; the list is refreshed either way.
baton_network_remove() {
  _bnr_net=$(baton_upstream_host "$1") || return 1
  _bnr_rc=0
  if docker network inspect "$_bnr_net" >/dev/null 2>&1; then
    if baton_network_has_nginx "$_bnr_net"; then
      docker network disconnect "$_bnr_net" "$BATON_NGINX_CONTAINER" || _bnr_rc=1
    fi
    if [ "$_bnr_rc" -eq 0 ]; then
      echo "[project-network] Removing network $_bnr_net" >&2
      docker network rm "$_bnr_net" >/dev/null || _bnr_rc=1
    fi
  fi
  baton_network_write_orchestrator_list || _bnr_rc=1
  return "$_bnr_rc"
}

# $1 project, $2 APP_SERVICE, $3 output file. Write the compose override that
# attaches APP_SERVICE to baton-<project> under the alias baton-<project>.
# `default` is listed because a service with a networks key is no longer
# attached to the project's default network implicitly.
baton_network_write_override() {
  _bnwo_net=$(baton_upstream_host "$1") || return 1
  if ! baton_check_app_service "$2"; then
    echo "[project-network] ERROR: APP_SERVICE '$2' is not a valid compose service name" >&2
    return 1
  fi
  mkdir -p "$(dirname "$3")" || return 1
  {
    echo "# Generated by baton for project $1. Do not edit."
    echo "services:"
    echo "  $2:"
    echo "    networks:"
    echo "      default: {}"
    echo "      $_bnwo_net:"
    echo "        aliases:"
    echo "          - $_bnwo_net"
    echo "networks:"
    echo "  $_bnwo_net:"
    echo "    external: true"
  } > "$3"
}

# $1 project, then container ids. Check what Docker actually attached: every
# network must be baton-<project> or a network of the container's own compose
# project, and network_mode may only borrow a container of the same project.
baton_network_verify() {
  _bnv_net=$(baton_upstream_host "$1") || return 1
  shift
  _bnv_bad=0
  for _bnv_c in "$@"; do
    _bnv_proj=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.project"}}' "$_bnv_c") || return 1
    _bnv_name=$(docker inspect -f '{{.Name}}' "$_bnv_c") || return 1
    _bnv_name=${_bnv_name#/}
    _bnv_mode=$(docker inspect -f '{{.HostConfig.NetworkMode}}' "$_bnv_c") || return 1
    case $_bnv_mode in
      host|bridge|default)
        echo "[project-network] ERROR: $_bnv_name uses network mode $_bnv_mode" >&2
        _bnv_bad=1
        continue
        ;;
      container:*)
        _bnv_peer=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.project"}}' "${_bnv_mode#container:}" 2>/dev/null) || _bnv_peer=
        if [ -z "$_bnv_proj" ] || [ "$_bnv_peer" != "$_bnv_proj" ]; then
          echo "[project-network] ERROR: $_bnv_name shares the network of a container outside its project" >&2
          _bnv_bad=1
        fi
        continue
        ;;
    esac
    _bnv_nets=$(docker inspect -f '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}' "$_bnv_c") || return 1
    for _bnv_n in $_bnv_nets; do
      [ "$_bnv_n" = "$_bnv_net" ] && continue
      [ "$_bnv_n" = none ] && continue
      _bnv_nproj=$(docker network inspect -f '{{index .Labels "com.docker.compose.project"}}' "$_bnv_n" 2>/dev/null) || _bnv_nproj=
      if [ -n "$_bnv_proj" ] && [ "$_bnv_nproj" = "$_bnv_proj" ]; then
        continue
      fi
      echo "[project-network] ERROR: $_bnv_name is attached to network $_bnv_n, which is not this project's" >&2
      _bnv_bad=1
    done
  done
  return "$_bnv_bad"
}
