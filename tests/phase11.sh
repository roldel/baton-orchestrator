# Phase 11 — per-project networks: names, override, network lifecycle,
# isolation check, compose guard rules. Docker is a stub that keeps state in
# a directory: net/<name>/{label,internal,compose,containers}, ctr/<id>/*.

phase11_docker_stub() {
  cat > "$1" <<'STUB'
#!/bin/sh
S=$PHASE11_STATE
echo "$*" >> "$S/calls"
case "$1 $2" in
  "network inspect")
    if [ "$3" = -f ]; then
      n=$5
      [ -d "$S/net/$n" ] || exit 1
      case $4 in
        *Containers*) printf '%s\n' "$(cat "$S/net/$n/containers" 2>/dev/null)" ;;
        *baton.project*) cat "$S/net/$n/label" 2>/dev/null; echo ;;
        *Internal*) cat "$S/net/$n/internal" 2>/dev/null; echo ;;
        *com.docker.compose.project*) cat "$S/net/$n/compose" 2>/dev/null; echo ;;
      esac
      exit 0
    fi
    [ -d "$S/net/$3" ] ;;
  "network create")
    n=$6
    mkdir -p "$S/net/$n"
    echo true > "$S/net/$n/internal"
    echo "${5#baton.project=}" > "$S/net/$n/label" ;;
  "network connect")
    printf ' %s' "$4" >> "$S/net/$3/containers" ;;
  "network disconnect")
    : > "$S/net/$3/containers" ;;
  "network rm")
    rm -rf "$S/net/$3" ;;
  "network ls")
    for d in "$S"/net/*; do
      [ -f "$d/label" ] && basename "$d"
    done
    exit 0 ;;
  "inspect -f")
    c=$4
    [ -d "$S/ctr/$c" ] || exit 1
    case $3 in
      *com.docker.compose.project*) cat "$S/ctr/$c/proj" ;;
      *NetworkMode*) cat "$S/ctr/$c/mode" ;;
      *.Name*) echo "/$c" ;;
      *Networks*) cat "$S/ctr/$c/nets" ;;
    esac ;;
  *) exit 0 ;;
esac
STUB
  chmod 755 "$1"
}

phase11_ctr() { # id project mode nets...
  _p11c=$PHASE11_STATE/ctr/$1
  mkdir -p "$_p11c"
  echo "$2" > "$_p11c/proj"
  echo "$3" > "$_p11c/mode"
  shift 3
  echo "$*" > "$_p11c/nets"
}

phase11_net() { # name compose-project
  mkdir -p "$PHASE11_STATE/net/$1"
  echo "$2" > "$PHASE11_STATE/net/$1/compose"
}

phase11() {
  _p11=$(mktemp -d)
  PHASE11_STATE=$_p11/state
  export PHASE11_STATE
  mkdir -p "$PHASE11_STATE/net" "$PHASE11_STATE/ctr" "$_p11/bin" "$_p11/base/orchestrator"
  phase11_docker_stub "$_p11/bin/docker"
  _p11_path=$PATH
  PATH="$_p11/bin:$PATH"

  _p11_base=${BASE_DIR-}
  BASE_DIR=$_p11/base
  . "$ROOT/scripts/tools/helpers/project-network.sh"

  # --- names ---
  [ "$(baton_upstream_host dresskod)" = baton-dresskod ] || fail "phase11: upstream host for dresskod"
  for _p11_bad in Dress dress_kod -dress '' 'a;b' \
      abcdefghijabcdefghijabcdefghijabcdefghijabcdefghijabcdefgh; do
    if baton_upstream_host "$_p11_bad" >/dev/null 2>&1; then
      fail "phase11: project name '$_p11_bad' accepted"
    fi
  done
  baton_check_app_service django || fail "phase11: APP_SERVICE django rejected"
  baton_check_app_service web.1_a-b || fail "phase11: APP_SERVICE web.1_a-b rejected"
  for _p11_bad in '' -web baton-web 'web: {}' 'a b'; do
    if baton_check_app_service "$_p11_bad"; then
      fail "phase11: APP_SERVICE '$_p11_bad' accepted"
    fi
  done
  ok "phase11: upstream host and APP_SERVICE names"

  # --- override ---
  baton_network_write_override dresskod django "$_p11/override.yml" || fail "phase11: override not written"
  printf '%s\n' \
    '# Generated by baton for project dresskod. Do not edit.' \
    'services:' '  django:' '    networks:' '      default: {}' \
    '      baton-dresskod:' '        aliases:' '          - baton-dresskod' \
    'networks:' '  baton-dresskod:' '    external: true' > "$_p11/override.want"
  cmp -s "$_p11/override.yml" "$_p11/override.want" || fail "phase11: override content differs"
  if baton_network_write_override dresskod 'x: {}' "$_p11/bad.yml" 2>/dev/null; then
    fail "phase11: override accepted an unsafe APP_SERVICE"
  fi
  ok "phase11: compose override attaches APP_SERVICE with the baton alias"

  # --- ensure / orchestrator list / remove ---
  baton_network_ensure dresskod 2>/dev/null || fail "phase11: ensure failed"
  grep -qx 'network create --internal --label baton.project=dresskod baton-dresskod' "$PHASE11_STATE/calls" \
    || fail "phase11: network not created as internal with the baton label"
  grep -qx 'network connect baton-dresskod ingress-nginx' "$PHASE11_STATE/calls" \
    || fail "phase11: nginx not attached"
  _p11_list=$(baton_network_orchestrator_file)
  grep -qx '      baton-dresskod: {}' "$_p11_list" || fail "phase11: orchestrator list lacks the network"
  : > "$PHASE11_STATE/calls"
  baton_network_ensure dresskod 2>/dev/null || fail "phase11: second ensure failed"
  if grep -q 'network create\|network connect' "$PHASE11_STATE/calls"; then
    fail "phase11: ensure is not idempotent"
  fi
  ok "phase11: ensure creates an internal network, attaches nginx, writes the list"

  mkdir -p "$PHASE11_STATE/net/baton-shop"
  echo false > "$PHASE11_STATE/net/baton-shop/internal"
  echo shop > "$PHASE11_STATE/net/baton-shop/label"
  if baton_network_ensure shop 2>/dev/null; then
    fail "phase11: ensure accepted a non-internal network"
  fi
  rm -rf "$PHASE11_STATE/net/baton-shop"
  mkdir -p "$PHASE11_STATE/net/baton-shop"
  echo true > "$PHASE11_STATE/net/baton-shop/internal"
  if baton_network_ensure shop 2>/dev/null; then
    fail "phase11: ensure accepted a network baton did not create"
  fi
  rm -rf "$PHASE11_STATE/net/baton-shop"
  ok "phase11: ensure refuses a network baton did not create"

  baton_network_remove dresskod 2>/dev/null || fail "phase11: remove failed"
  grep -qx 'network disconnect baton-dresskod ingress-nginx' "$PHASE11_STATE/calls" \
    || fail "phase11: nginx not detached before removal"
  [ ! -d "$PHASE11_STATE/net/baton-dresskod" ] || fail "phase11: network not removed"
  [ ! -f "$_p11_list" ] || fail "phase11: orchestrator list kept a removed network"
  baton_network_remove dresskod 2>/dev/null || fail "phase11: removing a missing network failed"
  ok "phase11: remove detaches nginx, deletes the network, refreshes the list"

  # --- isolation check after up ---
  baton_network_ensure dresskod 2>/dev/null || fail "phase11: ensure failed"
  phase11_net dresskod_default dresskod
  phase11_net shop_default shop
  phase11_ctr app dresskod dresskod_default "dresskod_default baton-dresskod"
  phase11_ctr db dresskod dresskod_default "dresskod_default"
  phase11_ctr side dresskod container:db ""
  baton_network_verify dresskod app db side 2>/dev/null || fail "phase11: a clean project failed the check"
  phase11_ctr spy dresskod dresskod_default "dresskod_default shop_default"
  if baton_network_verify dresskod app spy 2>/dev/null; then
    fail "phase11: another project's network was allowed"
  fi
  phase11_ctr br dresskod bridge "bridge"
  if baton_network_verify dresskod br 2>/dev/null; then
    fail "phase11: the default bridge was allowed"
  fi
  phase11_ctr shopapp shop shop_default "shop_default"
  phase11_ctr borrow dresskod container:shopapp ""
  if baton_network_verify dresskod borrow 2>/dev/null; then
    fail "phase11: borrowing another project's network stack was allowed"
  fi
  ok "phase11: isolation check after up"

  # --- compose guard ---
  . "$ROOT/scripts/tools/helpers/compose-guard.sh"
  mkdir -p "$_p11/proj"
  _p11_cfg() { printf '%s\n' "$@" > "$_p11/cfg.yml"; }
  _p11_cfg 'name: dresskod' 'services:' '  django:' '    networks:' '      default: null' \
    '  side:' '    network_mode: service:django' \
    'networks:' '  default:' '    name: dresskod_default' \
    'volumes:' '  data:' '    external: true' '    name: shared_data'
  baton_compose_config_allowed "$_p11/cfg.yml" "$_p11/proj" 2>/dev/null \
    || fail "phase11: guard rejected a clean config (service: mode, external volume)"
  for _p11_case in \
      'networks:|  other:|    external: true|    name: baton-shop' \
      'networks:|  legacy:|    external: true|    name: internal_proxy_pass_network' \
      'services:|  web:|    network_mode: bridge' \
      'services:|  web:|    network_mode: container:shop-app-1' \
      'services:|  web:|    container_name: baton-shop' \
      'services:|  web:|    hostname: baton-shop' \
      'services:|  web:|    networks:|      default:|        aliases:|          - baton-shop' \
      'services:|  baton-shop:|    image: x'; do
    printf '%s\n' "$_p11_case" | tr '|' '\n' > "$_p11/cfg.yml"
    if baton_compose_config_allowed "$_p11/cfg.yml" "$_p11/proj" 2>/dev/null; then
      fail "phase11: guard accepted: $_p11_case"
    fi
  done
  ok "phase11: guard rejects external networks, shared network modes, baton- names"

  # --- compose-cmd: up needs --project ---
  touch "$_p11/proj/docker-compose.yml"
  if sh "$ROOT/scripts/tools/helpers/compose-cmd.sh" "$_p11/proj" up -d > "$_p11/up.out" 2>&1; then
    fail "phase11: compose-cmd ran up without --project"
  fi
  grep -q 'up requires --project' "$_p11/up.out" || fail "phase11: compose-cmd up error unclear"
  ok "phase11: compose-cmd refuses up without --project"

  # --- wiring ---
  grep -q -- '--project "$PROJECT" up' "$ROOT/scripts/tools/projects/restart-containers.sh" \
    || fail "phase11: restart-containers does not pass --project"
  [ "$(grep -c -- '--project "$PROJECT" up' "$ROOT/scripts/tools/webhook/handle-webhook.sh")" -eq 2 ] \
    || fail "phase11: webhook redeploy does not pass --project to both up calls"
  grep -q 'baton_network_remove' "$ROOT/scripts/cmd/stand-down.sh" \
    || fail "phase11: stand-down does not remove the network"
  grep -q 'baton_orchestrator_compose up' "$ROOT/scripts/cmd/orchestrator-compose-respawn.sh" \
    || fail "phase11: orchestrator respawn does not use the network list"
  if grep -rq 'DOCKER_NETWORK_SERVICE_ALIAS\|internal_proxy_pass_network' \
      "$ROOT/example-project" "$ROOT/orchestrator/docker-compose.yml"; then
    fail "phase11: examples or orchestrator still use the shared network"
  fi
  ok "phase11: wiring"

  PATH=$_p11_path
  BASE_DIR=$_p11_base
  rm -rf "$_p11"
  unset PHASE11_STATE
}

phase11
